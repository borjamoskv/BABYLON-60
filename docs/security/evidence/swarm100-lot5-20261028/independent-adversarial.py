"""Lot5 independent checks: temporary SQLite/Fernet; native IPC blocked before import."""
import asyncio
from dataclasses import replace
import hashlib
import json
import os
from pathlib import Path
import sqlite3
import sys
import tempfile
import types


ROOT = Path(__file__).absolute().parents[4]
SOURCE = ROOT / '01_KISH_ENGINE/babylon60/bft/ledger_actor.py'
EVIDENCE = Path(__file__).absolute().parent
RESULTS = []


async def bounded(awaitable):
    return await asyncio.wait_for(asyncio.shield(awaitable), 5)


def main():
    source_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    with tempfile.TemporaryDirectory(prefix='lot5-independent-') as temporary:
        workspace = Path(temporary)
        os.environ['HOME'] = temporary
        os.environ.pop('CORTEX_VAULT_KEY', None)
        os.chdir(temporary)
        sys.modules['strike_rs'] = None
        package = types.ModuleType('babylon60')
        package.__path__ = [str(ROOT / '01_KISH_ENGINE/babylon60')]
        sys.modules['babylon60'] = package
        from cryptography.fernet import Fernet
        from babylon60.bft.ledger_actor import BFTLedgerActor, LedgerEvent

        def event(index=1, **changes):
            return replace(LedgerEvent('fixture', str(index), 'CREATED', {'index': index},
                                       'fixture', 'fixture', 'events', str(index)), **changes)

        def rows(path):
            with sqlite3.connect(path) as db:
                return db.execute('SELECT * FROM ledger_entries ORDER BY seq').fetchall()

        async def finish(actor):
            await bounded(actor.stop())
            await bounded(actor._queue.join())

        async def rejected(future):
            try:
                await bounded(future)
            except Exception as error:
                return type(error).__name__
            raise AssertionError('Expected failed accepted request')

        async def empty_created_at():
            actor = BFTLedgerActor(workspace / 'empty-time.db')
            await actor.start()
            try:
                first = await bounded(actor.append(event(created_at='')))
                assert await bounded(actor.append(event(created_at=''))) == first
                assert len(rows(actor._db_path)) == 1
            finally:
                await finish(actor)
            return 'Empty timestamp retains autogenerated-date retry semantics.'

        async def cancelled_stop():
            actor = BFTLedgerActor(workspace / 'cancelled-stop.db')
            entered, release = asyncio.Event(), asyncio.Event()
            original = actor._process

            async def held(*args):
                entered.set()
                await release.wait()
                return await original(*args)

            actor._process = held
            await actor.start()
            pending = actor.append(event())
            await bounded(entered.wait())
            stopping = asyncio.create_task(actor.stop())
            try:
                await bounded(actor._stop_event.wait())
                try:
                    actor.append(event(2))
                except RuntimeError:
                    pass
                else:
                    raise AssertionError('Admission remained open during stop')
                stopping.cancel()
                outcome = await asyncio.gather(stopping, return_exceptions=True)
                assert isinstance(outcome[0], asyncio.CancelledError)
            finally:
                release.set()
                await finish(actor)
            assert (await bounded(pending))['seq'] == 1
            return 'Cancelled stop caller cannot abort accepted work; admission is closed.'

        async def commit_barrier(cancel_future=False):
            actor = BFTLedgerActor(workspace / ('cancel-future.db' if cancel_future else 'cancel-worker.db'))
            entered, release = asyncio.Event(), asyncio.Event()
            original = actor._execute_insert_tx

            class Proxy:
                def __init__(self, db):
                    self.db = db
                def __getattr__(self, name):
                    return getattr(self.db, name)
                async def commit(self):
                    assert self.db.in_transaction
                    entered.set()
                    await release.wait()
                    return await self.db.commit()

            async def held(db, *args, **kwargs):
                return await original(Proxy(db), *args, **kwargs)

            actor._execute_insert_tx = held
            await actor.start()
            first = actor.append(event())
            second = actor.append(event(2))
            try:
                await bounded(entered.wait())
                if cancel_future:
                    first.cancel()
                else:
                    actor._task.cancel()
                    actor._task.cancel()
                release.set()
                if cancel_future:
                    assert (await bounded(second))['seq'] == 2
                    assert first.cancelled()
                    assert len(rows(actor._db_path)) == 2
                else:
                    assert (await bounded(first))['seq'] == 1
                    assert await rejected(second) == 'RuntimeError'
                    assert len(rows(actor._db_path)) == 1
            finally:
                release.set()
                await finish(actor)
            assert await actor.verify_chain()
            return ('Cancelled result future does not abort its accepted transaction or kill the worker.'
                    if cancel_future else 'Repeated worker cancellation waits for in-flight commit; queued future fails explicitly.')

        async def failed_rollback():
            actor = BFTLedgerActor(workspace / 'failed-rollback.db')
            original = actor._execute_insert_tx

            class Proxy:
                def __init__(self, db):
                    self.db = db
                def __getattr__(self, name):
                    return getattr(self.db, name)
                async def rollback(self):
                    raise sqlite3.OperationalError('fixture rollback failure')

            async def broken(db, *args, **kwargs):
                return await original(Proxy(db), *args, **kwargs)

            actor._execute_insert_tx = broken
            await actor.start()
            failed, queued = actor.append(event(stream='')), actor.append(event(2))
            try:
                assert await rejected(failed) == 'RuntimeError'
                assert await rejected(queued) == 'RuntimeError'
            finally:
                await finish(actor)
            assert actor._state == 'failed'
            assert rows(actor._db_path) == []
            return 'Unconfirmed rollback poisons worker, fails queued requests, and connection close leaves no partial row.'

        async def initialization_failure():
            actor = BFTLedgerActor(workspace / 'init-failure.db')
            initialize = actor._init_db

            async def broken(db):
                await initialize(db)
                raise RuntimeError('fixture init failure')

            actor._init_db = broken
            await actor.start()
            requests = [actor.append(event(i)) for i in range(3)]
            for request in requests:
                assert await rejected(request) == 'RuntimeError'
            await finish(actor)
            actor._init_db = initialize
            await actor.start()
            try:
                assert (await bounded(actor.append(event(4))))['seq'] == 1
            finally:
                await finish(actor)
            return 'Startup failure terminates all accepted requests; explicit restart recovers with a fresh queue.'

        async def before_first_worker_step():
            actor = BFTLedgerActor(workspace / 'before-first-step.db')
            await actor.start()
            requests = [actor.append(event(i)) for i in range(3)]
            actor._task.cancel()
            for request in requests:
                assert await rejected(request) == 'RuntimeError'
            await finish(actor)
            assert not actor._db_path.exists()
            return 'Done callback fails accepted requests even when worker was cancelled before entering its body.'

        async def capacity_and_cancel():
            actor = BFTLedgerActor(workspace / 'capacity.db')
            entered, release = asyncio.Event(), asyncio.Event()
            initialize = actor._init_db

            async def held(db):
                await initialize(db)
                entered.set()
                await release.wait()

            actor._init_db = held
            await actor.start()
            await bounded(entered.wait())
            requests = [actor.append(event(i)) for i in range(actor._queue.maxsize)]
            try:
                try:
                    actor.append(event(10000))
                except asyncio.QueueFull:
                    pass
                else:
                    raise AssertionError('Queue capacity was not enforced')
                actor._task.cancel()
                results = await bounded(asyncio.gather(*requests, return_exceptions=True))
                assert len(results) == 4096 and all(isinstance(r, RuntimeError) for r in results)
            finally:
                release.set()
                await finish(actor)
            assert rows(actor._db_path) == []
            return 'All 4096 accepted queued requests terminate on initialization cancellation; overflow is rejected.'

        async def key_and_metadata_rejections():
            actor = BFTLedgerActor(workspace / 'keys.db')
            key = Fernet.generate_key().decode()
            os.environ['CORTEX_VAULT_KEY'] = key
            await actor.start()
            try:
                original = await bounded(actor.append(event()))
                before = rows(actor._db_path)
                os.environ.pop('CORTEX_VAULT_KEY')
                assert await rejected(actor.append(event())) == 'ValueError'
                os.environ['CORTEX_VAULT_KEY'] = Fernet.generate_key().decode()
                assert await rejected(actor.append(event())) == 'ValueError'
                os.environ['CORTEX_VAULT_KEY'] = key
                assert await rejected(actor.append(event(event_type='DIFFERENT'))) == 'ValueError'
                assert await bounded(actor.append(event())) == original
                assert rows(actor._db_path) == before
                assert (await bounded(actor.append(event(2))))['seq'] == 2
            finally:
                await finish(actor)
                os.environ.pop('CORTEX_VAULT_KEY', None)
            return 'Absent/wrong keys and changed semantics reject without rewriting original ciphertext; later valid requests succeed.'

        checks = [
            ('empty_created_at', empty_created_at), ('cancelled_stop', cancelled_stop),
            ('worker_cancel_during_commit', commit_barrier),
            ('future_cancel_during_commit', lambda: commit_barrier(True)),
            ('failed_rollback', failed_rollback), ('startup_failure_restart', initialization_failure),
            ('cancel_before_worker_entry', before_first_worker_step),
            ('queue_capacity_and_terminal_futures', capacity_and_cancel),
            ('key_and_metadata_rejections', key_and_metadata_rejections),
        ]
        for name, function in checks:
            try:
                detail = asyncio.run(function())
                RESULTS.append(dict(name=name, status='PASS', detail=detail))
            except Exception as error:
                RESULTS.append(dict(name=name, status='FAIL', error=repr(error)))

        def multiple_loops():
            key = Fernet.generate_key().decode()
            os.environ['CORTEX_VAULT_KEY'] = key
            actor = BFTLedgerActor(workspace / 'multiple-loops.db')
            async def run():
                await actor.start()
                try:
                    return await bounded(actor.append(event()))
                finally:
                    await finish(actor)
            try:
                first = asyncio.run(run())
                original = rows(actor._db_path)
                assert asyncio.run(run()) == first
                assert asyncio.run(run()) == first
                assert rows(actor._db_path) == original
            finally:
                os.environ.pop('CORTEX_VAULT_KEY', None)
            return 'One actor reuses three distinct asyncio.run loops; encrypted retry keeps original row/result.'

        try:
            RESULTS.append(dict(name='encrypted_retry_across_event_loops', status='PASS', detail=multiple_loops()))
        except Exception as error:
            RESULTS.append(dict(name='encrypted_retry_across_event_loops', status='FAIL', error=repr(error)))
    final_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    report = dict(source_sha256=source_hash, final_source_sha256=final_hash,
                  source_stable=source_hash == final_hash, checks=RESULTS,
                  passed=sum(r['status'] == 'PASS' for r in RESULTS),
                  failed=sum(r['status'] == 'FAIL' for r in RESULTS),
                  scope='Temporary SQLite and ephemeral software Fernet keys only; strike_rs blocked before import, no operator stores, Rekor, hardware or ATTESTED.')
    (EVIDENCE / 'independent-adversarial.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))
    return 0 if not report['failed'] and report['source_stable'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
