import ast
import logging
from typing import Any

logger = logging.getLogger(__name__)


class JITSandboxViolation(Exception):
    """Raised when an agent attempts to execute an illegal AST node."""


class ASTSecurityScanner(ast.NodeVisitor):
    """
    Scans an AST for forbidden nodes or attributes (e.g., eval, exec, __import__, os).
    """

    FORBIDDEN_NAMES = {
        "eval",
        "exec",
        "__import__",
        "open",
        "getattr",
        "setattr",
        "delattr",
        "compile",
    }
    FORBIDDEN_IMPORTS = {"os", "sys", "subprocess", "socket", "requests", "shutil"}

    def visit_Call(self, node: ast.Call) -> None:
        if isinstance(node.func, ast.Name) and node.func.id in self.FORBIDDEN_NAMES:
            raise JITSandboxViolation(f"Prohibited function call detected: {node.func.id}")
        if isinstance(node.func, ast.Attribute) and node.func.attr.startswith("__"):
            raise JITSandboxViolation(f"Prohibited Dunder attribute: {node.func.attr}")
        self.generic_visit(node)

    def visit_Import(self, node: ast.Import) -> None:
        for alias in node.names:
            if alias.name.split(".")[0] in self.FORBIDDEN_IMPORTS:
                raise JITSandboxViolation(f"Prohibited import: {alias.name}")
        self.generic_visit(node)

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        if node.module and node.module.split(".")[0] in self.FORBIDDEN_IMPORTS:
            raise JITSandboxViolation(f"Prohibited import (from): {node.module}")
        self.generic_visit(node)

    def visit_Attribute(self, node: ast.Attribute) -> None:
        if node.attr.startswith("__"):
            raise JITSandboxViolation(f"Prohibited dunder attribute access: {node.attr}")
        self.generic_visit(node)


class SandboxJIT:
    """
    Executes agent-generated code inside a restricted globals namespace.
    """

    def __init__(self, allowed_globals: dict[str, Any] | None = None):
        self.allowed_globals = allowed_globals or {
            "__builtins__": {
                "print": print,
                "len": len,
                "range": range,
                "str": str,
                "int": int,
                "float": float,
                "bool": bool,
                "list": list,
                "dict": dict,
                "set": set,
                "tuple": tuple,
                "isinstance": isinstance,
                "sum": sum,
                "max": max,
                "min": min,
                "abs": abs,
                "round": round,
                "Exception": Exception,
                "ValueError": ValueError,
                "TypeError": TypeError,
            }
        }

    def execute(self, code_str: str, context: dict[str, Any] | None = None) -> dict[str, Any]:
        """
        Parses the code, statically verifies the AST, and then executes it.
        """
        try:
            tree = ast.parse(code_str)
        except SyntaxError as e:
            logger.error("SandboxJIT SyntaxError: %s", e)
            raise JITSandboxViolation(f"SyntaxError in the proposed code: {e}")

        # 1. Static security scan
        scanner = ASTSecurityScanner()
        scanner.visit(tree)

        # 2. Configurar el espacio de memoria (Memory Space)
        exec_globals = dict(self.allowed_globals)
        exec_globals["__builtins__"] = {}
        exec_locals = dict(context) if context else {}

        # 3. Ejecutar AST en Subproceso Aislado (Mónada de Caos)
        try:
            import json
            import os
            import subprocess
            import sys
            import tempfile

            source = ast.unparse(tree)
            wrapped = f"{source}\n\nimport json\n__res = {{k: v for k, v in locals().items() if not k.startswith('_') and isinstance(v, (str, int, float, bool, list, dict, type(None)))}}\nprint(json.dumps(__res))\n"

            with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False) as f:
                f.write(wrapped)
                f_name = f.name

            try:
                import signal
                proc = subprocess.Popen(
                    [sys.executable, f_name],
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                    env={},
                    start_new_session=True
                )
                try:
                    out, err = proc.communicate(timeout=5.0)
                except subprocess.TimeoutExpired:
                    os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
                    out, err = proc.communicate()
                    raise Exception("Execution exceeded 5.0s (Zombie Purged)")

                if proc.returncode != 0:
                    raise Exception(err or out)

                try:
                    exec_locals = json.loads(out)
                except json.JSONDecodeError:
                    exec_locals = {"raw_output": out}

                return exec_locals
            finally:
                try:
                    os.remove(f_name)
                except OSError:
                    pass

        except Exception as e:
            logger.error("SandboxJIT RuntimeException: %s", e)
            raise JITSandboxViolation(f"Sandbox execution error: {e}")
