# ─── Data Models ─────────────────────────────────────────────────────


@dataclass(frozen=True)
class SandboxVerdict:
    """Result of AST validation."""

    is_safe: bool
    violations: tuple[str, ...] = ()
    node_count: int = 0

    def __repr__(self) -> str:
        if self.is_safe:
            return f"SandboxVerdict(SAFE, {self.node_count} nodes)"
        return f"SandboxVerdict(UNSAFE, {len(self.violations)} violations)"


@dataclass()
class ExecResult:
    """Result of sandboxed execution.

    ``output`` is JSON round-tripped across the process boundary. Names
    whose values could not survive that trip are coerced to ``repr`` and
    listed in ``coerced_vars`` — never dropped without saying so.
    """

    success: bool
    output: dict[str, object] = field(default_factory=dict)
    stdout: str = ""
    error: str | None = None
    duration_ms: float = 0.0
    coerced_vars: tuple[str, ...] = ()


# ─── AST Sandbox ─────────────────────────────────────────────────────


class ASTSandbox:
    """Validates and optionally executes Python code in a restricted environment.

    Uses AST whitelist analysis. No subprocess, no Docker - pure AST + restricted exec.
    """

    def __init__(
        self,
        *,
        max_nodes: int = 500,
        max_depth: int = 20,
        timeout_seconds: int = 5,
    ):
        self._max_nodes = max_nodes
        self._max_depth = max_depth
        self._timeout = timeout_seconds

    def validate(self, code: str) -> SandboxVerdict:
        """Validate code via AST analysis without executing it.

        Returns SandboxVerdict indicating if code is safe to execute.
        """
        try:
            tree = ast.parse(code)
        except SyntaxError as e:
            return SandboxVerdict(
                is_safe=False,
                violations=(f"SyntaxError: {e}",),
            )

        violations: list[str] = []
        node_count = self._walk_and_check(tree, violations)
        self._collect_import_violations(tree, violations)

        depth = self._max_ast_depth(tree)
        if depth > self._max_depth:
            violations.append(f"AST depth {depth} exceeds max ({self._max_depth})")

        return SandboxVerdict(
            is_safe=len(violations) == 0,
            violations=tuple(violations),
            node_count=node_count,
        )

    def _walk_and_check(self, tree: ast.AST, violations: list[str]) -> int:
        """Walk AST nodes and collect violations. Returns node count."""
        node_count = 0
        for node in ast.walk(tree):
            node_count += 1
            if node_count > self._max_nodes:
                violations.append(f"Code exceeds max node count ({self._max_nodes})")
                break
            self._check_node(node, violations)
        return node_count

    @staticmethod
    def _check_node(node: ast.AST, violations: list[str]) -> None:
        """Check a single AST node against whitelist and blocklists."""
        if type(node) not in _ALLOWED_NODES:
            violations.append(f"Node type not allowed: {type(node).__name__}")
            return

        if isinstance(node, ast.Name) and node.id in _BLOCKED_NAMES:
            violations.append(f"Blocked builtin: '{node.id}'")

        if isinstance(node, ast.Attribute) and node.attr in _BLOCKED_ATTRS:
            violations.append(f"Blocked attribute: '{node.attr}'")

        if isinstance(node, ast.Call):
            func = node.func
            if isinstance(func, ast.Name) and func.id == "__import__":
                violations.append("Dynamic import via __import__()")

    @staticmethod
    def _collect_import_violations(tree: ast.AST, violations: list[str]) -> None:
        """Check for import statements (not in whitelist, validated separately)."""
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                module = ", ".join(a.name for a in node.names)
                violations.append(f"Import not allowed: '{module}'")
            elif isinstance(node, ast.ImportFrom):
                module = node.module or ""
                violations.append(f"Import not allowed: '{module}'")

    def safe_exec(self, code: str) -> ExecResult:
        """Validate and execute code in restricted environment.

        Returns ExecResult with captured output and namespace.
        """
        import time as _time

        # Step 1: Validate
        verdict = self.validate(code)
        if not verdict.is_safe:
            return ExecResult(
                success=False,
                error=f"Validation failed: {'; '.join(verdict.violations)}",
            )

        # Step 2: Execute in an isolated child process.
        # The restricted namespace is built inside that child from
        # _SAFE_BUILTIN_NAMES; nothing from this process is inherited.
        start = _time.monotonic()
        captured = StringIO()

        f_name: str | None = None
        result_path: str | None = None

        try:
            import json
            import os
            import subprocess
            import tempfile

            # Private result channel. Sandboxed code cannot reach it: it has
            # no imports and no `open`, and the wrapper source is not visible
            # from inside the restricted namespace.
            res_fd, result_path = tempfile.mkstemp(suffix=".json", prefix="sbx_res_")
            os.close(res_fd)

            wrapper = _WRAPPER_TEMPLATE.substitute(
                names=repr(_SAFE_BUILTIN_NAMES),
                code=repr(code),
                result_path=repr(result_path),
                max_repr=_MAX_COERCED_REPR,
            )

            with tempfile.NamedTemporaryFile(
                "w", suffix=".py", prefix="sbx_", delete=False
            ) as f:
                f.write(wrapper)
                f_name = f.name

            import signal

            proc = subprocess.Popen(
                [sys.executable, "-I", f_name],
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                env={},
                start_new_session=True,
            )
            try:
                out, err = proc.communicate(timeout=self._timeout)
            except subprocess.TimeoutExpired:
                os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
                out, err = proc.communicate()
                raise TimeoutError(
                    f"Execution exceeded {self._timeout}s (Zombie Purged)"
                )

            if proc.returncode != 0:
                raise RuntimeError(err or out)

            # stdout is entirely the user's. Results arrive out-of-band, so
            # nothing printed here can forge or erase them.
            captured.write(out)

            try:
                with open(result_path, encoding="utf-8") as fh:
                    payload = json.load(fh)
            except (OSError, ValueError) as exc:
                raise RuntimeError(f"Result channel unreadable: {exc}") from exc

            if not isinstance(payload, dict) or not isinstance(
                payload.get("vars"), dict
            ):
                raise RuntimeError("Result channel returned a malformed payload")

            user_vars: dict[str, object] = payload["vars"]
            coerced = tuple(payload.get("coerced", ()))

        except TimeoutError as e:
            return ExecResult(
                success=False,
                error=str(e),
                stdout=captured.getvalue(),
                duration_ms=(_time.monotonic() - start) * 1000,
            )
        except (ValueError, TypeError, OSError, KeyError, RuntimeError) as e:
            return ExecResult(
                success=False,
                error=f"{type(e).__name__}: {e}",
                stdout=captured.getvalue(),
                duration_ms=(_time.monotonic() - start) * 1000,
            )
        finally:
            for _path in (f_name, result_path):
                if _path:
                    try:
                        os.remove(_path)
                    except OSError:
                        pass

        return ExecResult(
            success=True,
            output=user_vars,
            stdout=captured.getvalue(),
            duration_ms=(_time.monotonic() - start) * 1000,
            coerced_vars=coerced,
        )

    @staticmethod
    def _max_ast_depth(node: ast.AST, depth: int = 0) -> int:
        """Compute max depth of AST tree."""
        max_d = depth
        for child in ast.iter_child_nodes(node):
            child_depth = ASTSandbox._max_ast_depth(child, depth + 1)
            if child_depth > max_d:
                max_d = child_depth
        return max_d
