def test_adversarial_corrupted_signature(sample_bundle_dir: str) -> None:
    """Caso Adversarial 3: Modificación o corrupción de la firma Ed25519."""
    exporter = EUAIActComplianceExporter(artifact_bundle_path=sample_bundle_dir)
    cert = exporter.generate_certificate(system_id="SYS-ADV-03", operator_name="Test Corp")

    tampered_cert = json.loads(json.dumps(cert))
    orig_sig = tampered_cert["signature"]["signature"]
    # Corromper los últimos 2 caracteres hex
    corrupted_sig = orig_sig[:-2] + ("00" if orig_sig[-2:] != "00" else "11")
    tampered_cert["signature"]["signature"] = corrupted_sig

    result = verify_compliance_certificate(tampered_cert)
    assert result["valid"] is False
    assert result["signature_valid"] is False
    assert "SIGNATURE_VERIFICATION_FAILED" in result["detail"]


def test_adversarial_expired_certificate(sample_bundle_dir: str) -> None:
    """Caso Adversarial 4: Certificado caducado (valid_until en el pasado)."""
    exporter = EUAIActComplianceExporter(artifact_bundle_path=sample_bundle_dir)
    # Generar con validez negativa o manipular valid_until
    cert = exporter.generate_certificate(system_id="SYS-EXPIRED-04", operator_name="Test Corp", validity_days=1)

    # Manipular fecha de expiración
    expired_cert = json.loads(json.dumps(cert))
    expired_cert["valid_until"] = "2021-01-01T00:00:00Z"

    result = verify_compliance_certificate(expired_cert)
    assert result["valid"] is False
    # La firma fallará o la comprobación de expiración fallará
    assert (
        "CERTIFICATE_EXPIRED" in result["detail"]
        or "PAYLOAD_HASH_MISMATCH" in result["detail"]
        or "SIGNATURE_VERIFICATION_FAILED" in result["detail"]
    )


def test_adversarial_revoked_certificate(sample_bundle_dir: str) -> None:
    """Caso Adversarial 5: Certificado revocado mediante CRL."""
    exporter = EUAIActComplianceExporter(artifact_bundle_path=sample_bundle_dir)
    cert = exporter.generate_certificate(system_id="SYS-REVOKE-05", operator_name="Test Corp")
    cert_id = cert["certificate_id"]

    # Sin CRL pasa
    assert verify_compliance_certificate(cert)["valid"] is True

    # Con CRL que incluye cert_id, debe ser rechazado
    res_crl = verify_compliance_certificate(cert, crl=[cert_id, "OTHER-REVOKED-ID"])
    assert res_crl["valid"] is False
    assert "CERTIFICATE_REVOKED" in res_crl["detail"]


