def test_verify_valid_certificate_standalone(sample_bundle_dir: str) -> None:
    """Verifica que un certificado válido generado por el exporter pasa la verificación independiente."""
    exporter = EUAIActComplianceExporter(artifact_bundle_path=sample_bundle_dir)
    cert = exporter.generate_certificate(
        system_id="SYS-VERIFY-01",
        operator_name="Kerckhoffs Enterprise",
        locale="es",
        validity_days=90,
    )

    result = verify_compliance_certificate(cert)
    assert result["valid"] is True
    assert result["signature_valid"] is True
    assert result["merkle_valid"] is True
    assert "CERTIFICATE_VALID_AND_VERIFIED" in result["detail"]


def test_verify_valid_certificate_from_file(sample_bundle_dir: str) -> None:
    """Verifica que la función pura acepta una ruta a un archivo JSON en disco."""
    exporter = EUAIActComplianceExporter(artifact_bundle_path=sample_bundle_dir)
    cert = exporter.generate_certificate(
        system_id="SYS-FILE-02",
        operator_name="Kerckhoffs Enterprise",
        validity_days=60,
    )

    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
        json.dump(cert, f, indent=2)
        cert_file = f.name

    try:
        result = verify_compliance_certificate(cert_file)
        assert result["valid"] is True
        assert result["signature_valid"] is True
        assert result["merkle_valid"] is True
    finally:
        if os.path.exists(cert_file):
            os.remove(cert_file)


def test_verify_with_sqlite_ledger(sample_bundle_dir: str) -> None:
    """Verifica un certificado junto con un ledger SQLite real recomputando hashes y Merkle root."""
    with tempfile.TemporaryDirectory() as ledger_dir:
        db_path = os.path.join(ledger_dir, "test_cortex.db")
        ledger = CortexPersistLedger(db_path)

        for i in range(1, 4):
            ledger.append_event(
                CortexEvent(
                    event_type="DECISION_RISK_AUDIT",
                    payload={"action_id": f"act_{i}", "score": 0.1 * i},
                    cortex_taint=f"taint_scope_{i}",
                )
            )

        attestation = ledger.get_state_attestation()
        assert attestation["integrity_verified"] is True
        merkle_root = attestation["merkle_root"]

        # Actualizar manifest con la raíz real del ledger
        manifest_path = os.path.join(sample_bundle_dir, "manifest.json")
        with open(manifest_path, "w", encoding="utf-8") as f:
            json.dump({"global_hash": merkle_root, "events_count": 3}, f)

        exporter = EUAIActComplianceExporter(artifact_bundle_path=sample_bundle_dir, ledger_path=db_path)
        cert = exporter.generate_certificate(
            system_id="SYS-SQLITE-03",
            operator_name="Audited Entity Corp",
            ledger_path=db_path,
        )

        # Verificación independiente contra el ledger
        result = verify_compliance_certificate(cert, ledger_path=db_path)
        assert result["valid"] is True
        assert result["signature_valid"] is True
        assert result["merkle_valid"] is True
        assert "LEDGER_VERIFIED" in result["detail"]


def test_verify_with_json_ledger(sample_bundle_dir: str) -> None:
    """Verifica un certificado con un ledger en formato JSON."""
    leaves = [
        "11" * 32,
        "22" * 32,
        "33" * 32,
    ]
    from babylon60.verifier.standalone_verify import build_cortex_merkle_tree

    computed_root = build_cortex_merkle_tree(leaves)

    with tempfile.TemporaryDirectory() as tmp_dir:
        json_ledger_path = os.path.join(tmp_dir, "ledger.json")
        with open(json_ledger_path, "w", encoding="utf-8") as f:
            json.dump({"leaves": leaves}, f)

        # Actualizar manifest
        manifest_path = os.path.join(sample_bundle_dir, "manifest.json")
        with open(manifest_path, "w", encoding="utf-8") as f:
            json.dump({"global_hash": computed_root}, f)

        exporter = EUAIActComplianceExporter(artifact_bundle_path=sample_bundle_dir)
        cert = exporter.generate_certificate(system_id="SYS-JSON-04", operator_name="Acme Corp")

        ev_result = verify_offline_evidence(json_ledger_path, expected_merkle_root=computed_root)
        assert ev_result["verified"] is True
        assert ev_result["merkle_root"] == computed_root

        result = verify_compliance_certificate(cert, ledger_path=json_ledger_path)
        assert result["valid"] is True
        assert result["merkle_valid"] is True


def test_adversarial_tampered_payload(sample_bundle_dir: str) -> None:
    """Caso Adversarial 1: Modificación de cualquier campo del payload invalida la firma Ed25519."""
    exporter = EUAIActComplianceExporter(artifact_bundle_path=sample_bundle_dir)
    cert = exporter.generate_certificate(
        system_id="SYS-ADV-01",
        operator_name="Original Honest Corp",
    )

    # El atacante modifica el operador
    tampered_cert = dict(cert)
    tampered_cert["operator"] = "Malicious Impersonator Corp"

    result = verify_compliance_certificate(tampered_cert)
    assert result["valid"] is False
    assert result["signature_valid"] is False
    assert "SIGNATURE_VERIFICATION_FAILED" in result["detail"] or "PAYLOAD_HASH_MISMATCH" in result["detail"]


