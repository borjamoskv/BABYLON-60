        "\t\t\t\tif err != nil {",
        f'\t\t\t\t\tt.Fatalf("Failed to dispatch {domain_name} primitives [%d,%d,%d]: %v", d, p, m, err)',
        "\t\t\t\t}",
        "\t\t\t\tcode := uint16(d)*100 + uint16(p)*10 + uint16(m)",
        f"\t\t\t\texecCount := {cfg['go_count']}(code)",
        "\t\t\t\tif execCount < 1 {",
        '\t\t\t\t\tt.Errorf("Expected execution count 1 for code %d, got %d", code, execCount)',
        "\t\t\t\t}",
        "\t\t\t\tcount++",
        "\t\t\t}",
        "\t\t}",
        "\t}",
        "\tif count != 1000 {",
        f'\t\tt.Fatalf("Expected 1000 {domain_name} primitives tested, got %d", count)',
        "\t}",
        f'\tt.Logf("✅ Successfully verified 100%% execution coverage across all 1000 {domain_name} Primitives.")',
