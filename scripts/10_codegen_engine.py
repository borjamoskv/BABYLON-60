def generate_python_test(
    domain_name: str, cfg: dict[str, Any], output_path: str
) -> None:
    module_name = domain_name.lower()
    if module_name == "constants":
        module_name = "fundamental_constants"
    elif module_name == "neuro":
        module_name = "neuro_chain"
    elif module_name == "tts":
        module_name = "tts_harness"
    lines = [
        "# Auto-generated by 10_codegen_engine.py. DO NOT EDIT.",
        "import unittest",
        f"from cortex.{module_name} import {cfg['py_dispatch']}, {cfg['py_state']}",
        "",
        f"class Test{domain_name}Kernel(unittest.TestCase):",
        f"    def test_{domain_name.lower()}_coverage(self):",
        f"        vec = {cfg['py_state']}()",
        "        count = 0",
        "        for d in range(10):",
        "            for p in range(10):",
        "                for m in range(10):",
        f"                    code, name, val = {cfg['py_dispatch']}(d, p, m, vec)",
        "                    self.assertEqual(code, d*100 + p*10 + m)",
        "                    count += 1",
        "        self.assertEqual(count, 1000)",
        f"        print(f'✅ Successfully verified 100% execution coverage for 1000 Python/{domain_name} Primitives.')",
        "",
        "if __name__ == '__main__':",
        "    unittest.main()",
        "",
    ]
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w") as f:
        f.write("\n".join(lines))


def main() -> None:
    for domain_name, cfg in CODEGEN_CONFIGS.items():
        yaml_path = cfg["yaml"]
        module_name = domain_name.lower()
        if module_name == "constants":
            module_name = "fundamental_constants"
        elif module_name == "neuro":
            module_name = "neuro_chain"
        elif module_name == "tts":
            module_name = "tts_harness"

        go_output = f"primitives/{module_name}.go"
        rust_output = f"src-tauri/src/{module_name}.rs"
        py_output = f"cortex/{module_name}.py"
        go_test_output = f"primitives/{module_name}_test.go"
        py_test_output = f"cortex/{module_name}_test.py"

        domains, primitives, modifiers = parse_yaml(yaml_path)
        generate_go(domain_name, cfg, domains, primitives, modifiers, go_output)
        generate_rust(domain_name, cfg, domains, primitives, modifiers, rust_output)
        generate_python(domain_name, cfg, domains, primitives, modifiers, py_output)
        generate_go_test(domain_name, cfg, go_test_output)
        generate_python_test(domain_name, cfg, py_test_output)
        print(f"✅ Generated C5-REAL topology for {domain_name}")


if __name__ == "__main__":
    main()
