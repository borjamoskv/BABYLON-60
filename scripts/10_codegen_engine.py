        "package primitives",
        "",
        "import (",
        '\t"testing"',
        ")",
        "",
        f"func Test{cfg['go_init'].replace('Init', '')}Coverage(t *testing.T) {{",
        f"\t{cfg['go_init']}()",
        f"\tvec := &{cfg['go_state']}{{}}",
        "\tcount := 0",
        "\tfor d := byte(0); d < 10; d++ {",
        "\t\tfor p := byte(0); p < 10; p++ {",
        "\t\t\tfor m := byte(0); m < 10; m++ {",
