"""Install a checkout-specific topology hook while chaining existing Git hooks.

Run from any directory: python3 scripts/guards/install_topology_hook.py
Generated hooks and their upstream path are stored only in this checkout's Git
metadata. Existing global hooks remain in place and keep their arguments, stdin
and exit codes. Rerun the installer when adding new hooks to the upstream folder.
Hook files are replaced atomically. Symbolic-link destinations are refused, and
linked worktrees require worktree-specific Git configuration.
"""

import argparse
import os
from pathlib import Path
import shlex
import subprocess
import sys
import tempfile

MARKER = "# Generated by BABYLON-60 install_topology_hook.py"
UPSTREAM_KEY = "babylon60.topologyUpstreamHooksPath"


def git(root: Path, *args: str, optional: bool = False) -> str:
    result = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, check=False)
    if optional and result.returncode == 1:
        return ""
    if result.returncode:
        raise RuntimeError(result.stderr.strip() or f"Git command failed: {args}")
    return result.stdout.strip()


def install(root: Path) -> tuple[Path, int]:
    root = Path(git(root, "rev-parse", "--show-toplevel"))
    git_dir = Path(git(root, "rev-parse", "--absolute-git-dir"))
    destination = git_dir / "topology-hooks"
    if destination.is_symlink() or (destination.exists() and not destination.is_dir()):
        raise RuntimeError("The generated hooks directory must be a real directory in Git metadata")
    scope = (
        "--worktree"
        if git(root, "config", "--bool", "--get", "extensions.worktreeConfig", optional=True) == "true"
        else "--local"
    )
    common_dir = Path(git(root, "rev-parse", "--git-common-dir"))
    if not common_dir.is_absolute():
        common_dir = root / common_dir
    if scope == "--local":
        count = sum(line.startswith("worktree ") for line in git(root, "worktree", "list", "--porcelain").splitlines())
        if common_dir.resolve() != git_dir.resolve() or count > 1:
            raise RuntimeError(
                "Multiple or linked worktrees require extensions.worktreeConfig=true; no shared configuration was changed"
            )
    upstream_value = git(root, "config", "--get", "core.hooksPath", optional=True)
    upstream = (
        Path(upstream_value).expanduser() if upstream_value else Path(git(root, "rev-parse", "--git-path", "hooks"))
    )
    if not upstream.is_absolute():
        upstream = root / upstream
    upstream = upstream.resolve()
    if upstream == destination.resolve():
        saved = git(root, "config", scope, "--get", UPSTREAM_KEY, optional=True)
        if not saved:
            raise RuntimeError("Installed hook has no saved upstream path; refusing to create a recursion")
        upstream = Path(saved)
    if upstream.resolve() == destination.resolve():
        raise RuntimeError("The upstream hooks directory cannot be the generated hooks directory")

    guard = root / "scripts/guards/verify_active_topology.py"
    subprocess.run([sys.executable, str(guard), "--repo-root", str(root)], cwd=root, check=True)
    names = {"pre-commit"}
    if upstream.is_dir():
        names.update(
            path.name
            for path in upstream.iterdir()
            if path.is_file() and os.access(path, os.X_OK) and not path.name.endswith(".sample")
        )
    scripts = {}
    for name in sorted(names):
        target = destination / name
        if target.is_symlink() or (
            target.exists() and not target.read_text().startswith("#!/bin/sh\n" + MARKER + "\n")
        ):
            raise RuntimeError(f"Refusing to overwrite an unrelated hook: {target}")
        commands = ["#!/bin/sh", MARKER]
        if name == "pre-commit":
            commands.extend(
                [
                    "repo_root=$(git rev-parse --show-toplevel) || exit 1",
                    f'{shlex.quote(sys.executable)} "$repo_root/scripts/guards/verify_active_topology.py" --staged || exit "$?"',
                ]
            )
        previous = shlex.quote(str(upstream / name))
        commands.extend([f"if [ -x {previous} ]; then", f'    exec {previous} "$@"', "fi", "exit 0"])
        scripts[name] = "\n".join(commands) + "\n"
    destination.mkdir(exist_ok=True)
    for name, content in scripts.items():
        target = destination / name
        temporary: Path | None = None
        try:
            with tempfile.NamedTemporaryFile(
                mode="w",
                encoding="utf-8",
                dir=destination,
                prefix=".topology-hook-",
                delete=False,
            ) as output:
                temporary = Path(output.name)
                output.write(content)
            temporary.chmod(0o755)
            os.replace(temporary, target)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
    git(root, "config", scope, UPSTREAM_KEY, str(upstream))
    git(root, "config", scope, "core.hooksPath", str(destination))
    return destination, len(names)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[2])
    args = parser.parse_args()
    try:
        directory, count = install(args.repo_root)
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print(error, file=sys.stderr)
        return 1
    print(f"PASS: topology pre-commit installed; {count} hooks chain to the previous directory ({directory})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
