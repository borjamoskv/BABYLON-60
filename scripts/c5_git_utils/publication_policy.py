"""Pre-push policy shared by the mirror and ship entry points."""

from collections.abc import Mapping
import hashlib
import os
from pathlib import Path
import re
import shlex
import stat
import subprocess
from urllib.parse import unquote, urlsplit

FORBIDDEN_COMMIT = "ce25e51caf18a03d69fc512421cbf059ddf61e6f"
FORBIDDEN_PATH = "leads_10000_enterprise_babylon60.csv"
TARGET_REF = "refs/heads/main"
HOOK_ERROR = "active pre-push hook requires a supported publication contract"
# The original installed gate is unversioned. Pin every byte preceding its
# checkout-specific chain, whose complete body and target are checked separately.
LEGACY_GATE_SHA256 = "b5e8f86150967956acfaad062af5f81516eb165ede31c4922d1a03045838caee"


def is_public_target(remote: str, url: str) -> bool:
    path = urlsplit(url).path if "://" in url else url
    path = unquote(path).rstrip("/").casefold().removesuffix(".git")
    return remote == "public" or path.endswith("borjamoskv/babylon-60")


def _active_hook(path: Path) -> bytes | None:
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise ValueError(HOOK_ERROR) from exc
    with os.fdopen(fd, "rb") as f:
        info = os.fstat(f.fileno())
        if not stat.S_ISREG(info.st_mode):
            raise ValueError(HOOK_ERROR)
        if not info.st_mode & 0o111:
            return None
        contents = f.read(32_769)
        if len(contents) > 32_768:
            raise ValueError(HOOK_ERROR)
        return contents


def check_source_hook() -> None:
    git_path = subprocess.check_output(["git", "rev-parse", "--path-format=absolute", "--git-path", "hooks/pre-push"])
    contents = _active_hook(Path(os.fsdecode(git_path).removesuffix("\n")))
    if contents is None:
        return

    configured = subprocess.run(
        ["git", "config", "--get", "babylon60.topologyUpstreamHooksPath"], capture_output=True, check=False
    )
    upstream_dir = Path(os.fsdecode(configured.stdout).removesuffix("\n"))
    if configured.returncode or not upstream_dir.is_absolute():
        raise ValueError(HOOK_ERROR)
    upstream = upstream_dir / "pre-push"
    target = os.fsencode(shlex.quote(str(upstream)))
    header = b"#!/bin/sh\n# Generated by BABYLON-60 install_topology_hook.py\n"
    chain = b"if [ -x " + target + b" ]; then\n"
    wrapper = header + chain + b"    exec " + target + b' "$@"\nfi\nexit 0\n'
    if contents != wrapper:
        suffix = b"\n" + chain + b'    printf "%s\\n" "$stdin_buf" | ' + target + b' "$@"\n    exit "$?"\nfi\nexit 0\n'
        if (
            not contents.endswith(suffix)
            or hashlib.sha256(contents.removesuffix(suffix)).hexdigest() != LEGACY_GATE_SHA256
        ):
            raise ValueError(HOOK_ERROR)
    # The isolated publisher cannot enforce an arbitrary additional executable.
    if _active_hook(upstream) is not None:
        raise ValueError(HOOK_ERROR)


def _oid(text: str) -> bool:
    return re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", text) is not None


def advertised_oid(advertisement: bytes, commit: str) -> str | None:
    if advertisement == b"":
        return None
    oid, sep, ref = advertisement.decode("ascii").removesuffix("\n").partition("\t")
    if not sep or ref != TARGET_REF or not _oid(oid) or len(oid) != len(commit) or not int(oid, 16):
        raise ValueError("invalid public destination ref advertisement")
    return oid


def check_public_history(
    commit: str,
    remote_oid: str | None,
    *,
    cwd: str | os.PathLike[str] | None = None,
    env: Mapping[str, str] | None = None,
) -> None:
    """Inspect exactly the advertised range, or all local ancestors if the remote tip is unavailable."""
    if not _oid(commit) or (remote_oid is not None and (not _oid(remote_oid) or len(remote_oid) != len(commit))):
        raise ValueError("invalid public history object ID")

    def git(*args: str, data: bytes | None = None) -> bytes:
        return subprocess.check_output(["git", "--no-replace-objects", *args], cwd=cwd, env=env, input=data)

    if git("rev-parse", "--is-shallow-repository").strip() != b"false":
        raise ValueError("public history requires complete ancestry")
    # Walk ancestry even when the forbidden object is missing. Git errors and
    # missing parents must stop publication rather than count as negative evidence.
    if FORBIDDEN_COMMIT.encode() in git("rev-list", "--full-history", commit).splitlines():
        raise ValueError("forbidden commit in public ancestry")
    if git("ls-tree", "-z", "--name-only", commit, "--", FORBIDDEN_PATH):
        raise ValueError("forbidden path in public tree")

    revision = commit
    if remote_oid is not None:
        object_type = git("cat-file", "--batch-check=%(objecttype)", data=(remote_oid + "\n").encode()).strip()
        if object_type == b"commit":
            revision = f"{remote_oid}..{commit}"
        elif object_type != (remote_oid + " missing").encode():
            raise ValueError("invalid public destination commit")
    if git("rev-list", "--full-history", "--max-count=1", revision, "--", FORBIDDEN_PATH):
        raise ValueError("forbidden path in outgoing public history")


def install_dispatch_hook(hooks_dir: Path, commit: str, target_ref: str, remote_oid: str | None) -> None:
    """Git supplies the actual ref advertisement to this private pre-push hook."""
    if target_ref != TARGET_REF or not _oid(commit):
        raise ValueError("invalid checked public ref")
    expected = "0" * len(commit) if remote_oid is None else remote_oid
    if not _oid(expected) or len(expected) != len(commit):
        raise ValueError("invalid checked public tip")
    hooks_dir.mkdir(mode=0o700)
    hook = hooks_dir / "pre-push"
    with hook.open("x", encoding="ascii") as f:
        f.write(
            "#!/bin/sh\n"
            "while read -r local_ref local_oid remote_ref remote_oid; do\n"
            f'    if [ "$local_oid" != "{commit}" ] || [ "$remote_ref" != "{target_ref}" ] '
            f'|| [ "$remote_oid" != "{expected}" ]; then\n'
            '        echo "Publication refused: public ref differs from checked update" >&2\n'
            "        exit 1\n"
            "    fi\n"
            "done\n"
        )
    hook.chmod(0o700)
    if not os.access(hook, os.X_OK):
        raise ValueError("public dispatch requires an executable pre-push hook")
