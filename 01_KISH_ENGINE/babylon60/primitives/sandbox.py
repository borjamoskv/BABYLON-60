# ─── Data Models ─────────────────────────────────────────────────────


@dataclass(frozen=True)
class SandboxVerdict:
    """Result of AST validation."""

    is_safe: bool
    violations: tuple[str, ...] = ()
    node_count: int = 0

    def __repr__(self) -> str:
        if self.is_safe:
            return f"SandboxVerdict(SAFE, {self.node_count} nodes)"
        return f"SandboxVerdict(UNSAFE, {len(self.violations)} violations)"


@dataclass()
class ExecResult:
    """Result of sandboxed execution."""

    success: bool
    output: dict[str, object] = field(default_factory=dict)
    stdout: str = ""
    error: str | None = None
    duration_ms: float = 0.0


# ─── AST Sandbox ─────────────────────────────────────────────────────


class ASTSandbox:
    """Validates and optionally executes Python code in a restricted environment.

    AST validation precedes execution in a disposable, resource-limited child.
    """

    def __init__(
        self,
        *,
        max_nodes: int = 500,
        max_depth: int = 20,
        timeout_seconds: int = 5,
        max_memory_bytes: int = 128 * 1024 * 1024,
        max_output_bytes: int = 65_536,
        max_result_bytes: int = 1_048_576,
    ) -> None:
        self._max_nodes = max_nodes
        self._max_depth = max_depth
        self._timeout = timeout_seconds
        for value in (timeout_seconds, max_memory_bytes, max_output_bytes, max_result_bytes):
            if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
                raise ValueError("Execution limits must be positive integers")
        if not 32 * 1024 * 1024 <= max_memory_bytes <= 1024 * 1024 * 1024:
            raise ValueError("Memory limit must be between 32 MiB and 1 GiB")
        if max_output_bytes > 1_048_576 or max_result_bytes > 1_048_576:
            raise ValueError("Output/result limits must not exceed 1 MiB")
        self._max_memory_bytes = max_memory_bytes
        self._max_output_bytes = max_output_bytes
        self._max_result_bytes = max_result_bytes

    def validate(self, code: str) -> SandboxVerdict:
        """Validate code via AST analysis without executing it.

        Returns SandboxVerdict indicating if code is safe to execute.
        """
        try:
            tree = ast.parse(code)
        except SyntaxError as e:
            return SandboxVerdict(
                is_safe=False,
                violations=(f"SyntaxError: {e}",),
            )

        violations: list[str] = []
        node_count = self._walk_and_check(tree, violations)
        self._collect_import_violations(tree, violations)

        depth = self._max_ast_depth(tree)
        if depth > self._max_depth:
            violations.append(f"AST depth {depth} exceeds max ({self._max_depth})")

        return SandboxVerdict(
            is_safe=len(violations) == 0,
            violations=tuple(violations),
            node_count=node_count,
        )

    def _walk_and_check(self, tree: ast.AST, violations: list[str]) -> int:
        """Walk AST nodes and collect violations. Returns node count."""
        node_count = 0
        for node in ast.walk(tree):
            node_count += 1
            if node_count > self._max_nodes:
                violations.append(f"Code exceeds max node count ({self._max_nodes})")
                break
            self._check_node(node, violations)
        return node_count

    @staticmethod
    def _check_node(node: ast.AST, violations: list[str]) -> None:
        """Check a single AST node against whitelist and blocklists."""
        if type(node) not in _ALLOWED_NODES:
            violations.append(f"Node type not allowed: {type(node).__name__}")
            return

        if isinstance(node, ast.Name) and node.id in _BLOCKED_NAMES:
            violations.append(f"Blocked builtin: '{node.id}'")

        if isinstance(node, ast.Attribute):
            if node.attr in _BLOCKED_ATTRS or node.attr.startswith("_"):
                violations.append(f"Blocked attribute: '{node.attr}'")

        if isinstance(node, ast.Call):
            func = node.func
            if isinstance(func, ast.Name) and func.id == "__import__":
                violations.append("Dynamic import via __import__()")

    @staticmethod
    def _collect_import_violations(tree: ast.AST, violations: list[str]) -> None:
        """Check for import statements (not in whitelist, validated separately)."""
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                module = ", ".join(a.name for a in node.names)
                violations.append(f"Import not allowed: '{module}'")
            elif isinstance(node, ast.ImportFrom):
                module = node.module or ""
                violations.append(f"Import not allowed: '{module}'")

    def safe_exec(self, code: str) -> ExecResult:
        """Run validated code in a disposable process with enforced limits.

        Linux RLIMIT_AS is required; other platforms reject before execution.
        This is a resource bound and restricted Python evaluator, not an OS
        access-control sandbox. Output values must be JSON-serializable.
        """
        start = time.monotonic()
        if len(code) > 65_536 or len(code.encode("utf-8")) > 65_536:
            return ExecResult(success=False, error="SOURCE_LIMIT_EXCEEDED")
        verdict = self.validate(code)
        if not verdict.is_safe:
            return ExecResult(success=False, error=f"Validation failed: {'; '.join(verdict.violations)}")
        request = {"code": code, "memory_bytes": self._max_memory_bytes,
                   "output_bytes": self._max_output_bytes, "result_bytes": self._max_result_bytes,
                   "max_nodes": self._max_nodes, "max_depth": self._max_depth}
        try:
            with tempfile.TemporaryDirectory(prefix="b60-eval-") as work:
                child = subprocess.run(
                    [sys.executable, "-I", os.path.abspath(__file__), "--bounded-worker"],
                    input=json.dumps(request), text=True, capture_output=True,
                    timeout=self._timeout, cwd=work,
                    env={"PATH": os.defpath, "PYTHONIOENCODING": "utf-8"},
                    check=False,
                )
            if child.returncode != 0:
                return ExecResult(success=False, error="WORKER_FAILED_OR_RESOURCE_LIMIT",
                                  duration_ms=(time.monotonic() - start) * 1000)
            response = json.loads(child.stdout)
            return ExecResult(success=bool(response["success"]), output=response.get("output", {}),
                              stdout=response.get("stdout", ""), error=response.get("error"),
                              duration_ms=(time.monotonic() - start) * 1000)
        except subprocess.TimeoutExpired:
            # subprocess.run kills and waits for this child before raising.
            return ExecResult(success=False, error="EXECUTION_TIMEOUT",
                              duration_ms=(time.monotonic() - start) * 1000)
        except (OSError, ValueError, KeyError, TypeError) as exc:
            return ExecResult(success=False, error=f"WORKER_PROTOCOL_ERROR: {type(exc).__name__}",
                              duration_ms=(time.monotonic() - start) * 1000)

    @staticmethod
    def _max_ast_depth(node: ast.AST, depth: int = 0) -> int:
        """Compute max depth of AST tree."""
        max_d = depth
        for child in ast.iter_child_nodes(node):
            child_depth = ASTSandbox._max_ast_depth(child, depth + 1)
            if child_depth > max_d:
                max_d = child_depth
        return max_d


class _OutputLimitError(Exception):
    pass


class _BoundedText(StringIO):
    def __init__(self, limit: int) -> None:
        super().__init__()
        self.limit = limit
        self.bytes_written = 0

    def write(self, text: str) -> int:
        size = len(text.encode("utf-8"))
        if self.bytes_written + size > self.limit:
            raise _OutputLimitError("OUTPUT_LIMIT_EXCEEDED")
        self.bytes_written += size
        return super().write(text)


def _execute_bounded(request: dict[str, Any]) -> dict[str, Any]:
    """Trusted worker entrypoint. Limits are applied before compiling user code."""
    if not sys.platform.startswith("linux"):
        return {"success": False, "error": "RESOURCE_LIMIT_UNAVAILABLE: Linux RLIMIT_AS required"}
    try:
        import resource

        limit = request["memory_bytes"]
        resource.setrlimit(resource.RLIMIT_AS, (limit, limit))
        if resource.getrlimit(resource.RLIMIT_AS) != (limit, limit):
            raise ValueError("Address-space limit was not applied")
    except (ImportError, OSError, ValueError):
        return {"success": False, "error": "RESOURCE_LIMIT_UNAVAILABLE"}
    verdict = ASTSandbox(max_nodes=request.get("max_nodes", 500),
                         max_depth=request.get("max_depth", 20)).validate(request["code"])
    if not verdict.is_safe:
        return {"success": False, "error": "WORKER_VALIDATION_FAILED"}
    names = ("abs all any bin bool chr dict divmod enumerate filter float format frozenset hash hex int "
             "isinstance issubclass iter len list map max min next oct ord pow range repr reversed round "
             "set slice sorted str sum tuple zip").split()
    import builtins

    allowed = {name: getattr(builtins, name) for name in names}
    captured = _BoundedText(request["output_bytes"])

    def bounded_print(*args: object, **kwargs: Any) -> None:
        if "file" in kwargs:
            raise ValueError("print(file=...) is not supported")
        print(*args, file=captured, **kwargs)

    allowed["print"] = bounded_print
    namespace: dict[str, Any] = {"__builtins__": allowed}
    try:
        exec(compile(request["code"], "<bounded-eval>", "exec"), namespace)  # nosec B102
        output = {k: v for k, v in namespace.items() if not k.startswith("_")}
        # Reject non-JSON objects and oversized/cyclic namespace data in the child.
        encoded = json.dumps(output, allow_nan=False)
        if len(encoded.encode("utf-8")) > request["result_bytes"]:
            return {"success": False, "error": "RESULT_LIMIT_EXCEEDED", "stdout": captured.getvalue()}
        return {"success": True, "output": json.loads(encoded), "stdout": captured.getvalue()}
    except _OutputLimitError:
        return {"success": False, "error": "OUTPUT_LIMIT_EXCEEDED", "stdout": captured.getvalue()}
    except MemoryError:
        return {"success": False, "error": "MEMORY_LIMIT_EXCEEDED"}
    except Exception as exc:
        # Do not serialize arbitrarily large exception messages or live objects.
        return {"success": False, "error": f"EXECUTION_ERROR: {type(exc).__name__}",
                "stdout": captured.getvalue()}


if __name__ == "__main__" and sys.argv[1:] == ["--bounded-worker"]:
    payload = json.loads(sys.stdin.read(400_000))
    print(json.dumps(_execute_bounded(payload), allow_nan=False))
