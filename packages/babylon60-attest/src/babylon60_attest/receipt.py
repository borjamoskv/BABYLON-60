# C5-REAL EXERGY CERTIFIED
"""
SCITT Receipt: the core attestation artifact.

A ScittReceipt is a self-contained, serializable proof that a specific
(prompt, output) pair was generated by a specific model at a specific time,
with a cryptographic binding (Merkle root) that makes post-hoc tampering
mathematically detectable.

Compatible with IETF SCITT RFC 9943 concepts: Claims, Receipts, and
Transparency Services.
"""
from __future__ import annotations

import json
import time
from dataclasses import dataclass, field, asdict
from typing import Any, Dict, Optional

from babylon60_attest.merkle import MerkleTree, sha3_256, sha3_256_str


@dataclass(frozen=True, slots=True)
class ScittReceipt:
    """
    Immutable attestation receipt for an LLM interaction.

    Fields:
        schema: Receipt schema identifier.
        operator_id: Identity of the entity operating the LLM.
        model: Model identifier (e.g., "claude-4-sonnet", "gpt-4o").
        prompt_digest: SHA3-256 of the prompt text.
        output_digest: SHA3-256 of the model output text.
        merkle_root: Merkle root binding prompt + output + metadata.
        attestation_digest: SHA3-256 of the canonical receipt (self-hash).
        timestamp_monotonic: Monotonic clock at receipt creation (no wall-clock).
        metadata: Optional operator-defined key-value metadata.
    """

    schema: str = "babylon60.llm.attestation/v1"
    operator_id: str = ""
    model: str = ""
    prompt_digest: str = ""
    output_digest: str = ""
    merkle_root: str = ""
    merkle_leaf_count: int = 0
    attestation_digest: str = ""
    timestamp_monotonic: float = 0.0
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        """Serialize to a plain dictionary."""
        return asdict(self)

    def to_json(self, indent: int = 2) -> str:
        """Serialize to canonical JSON (sorted keys, no ASCII escaping)."""
        return json.dumps(
            self.to_dict(),
            sort_keys=True,
            indent=indent,
            ensure_ascii=False,
        )

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "ScittReceipt":
        """Deserialize from a dictionary."""
        return cls(**{k: v for k, v in data.items() if k in cls.__dataclass_fields__})

    @classmethod
    def from_json(cls, text: str) -> "ScittReceipt":
        """Deserialize from a JSON string."""
        return cls.from_dict(json.loads(text))


def build_receipt(
    *,
    operator_id: str,
    model: str,
    prompt: str,
    output: str,
    metadata: Optional[Dict[str, Any]] = None,
) -> ScittReceipt:
    """
    Build a SCITT receipt for a single LLM interaction.

    The receipt cryptographically binds the prompt, output, model identifier,
    and operator identity into a single Merkle root. The attestation_digest
    is the SHA3-256 of the canonical (sorted, compact) JSON representation
    of the receipt's core fields, making the receipt self-verifying.

    Returns:
        A frozen ScittReceipt instance.
    """
    prompt_digest = sha3_256_str(prompt)
    output_digest = sha3_256_str(output)

    # Build Merkle tree over the attestation leaves
    leaves = [
        prompt_digest,
        output_digest,
        sha3_256_str(model),
        sha3_256_str(operator_id),
    ]
    tree = MerkleTree(leaves)

    ts = time.monotonic()

    # Build the core (pre-digest) receipt
    core = {
        "schema": "babylon60.llm.attestation/v1",
        "operator_id": operator_id,
        "model": model,
        "prompt_digest": prompt_digest,
        "output_digest": output_digest,
        "merkle_root": tree.root,
        "merkle_leaf_count": tree.leaf_count,
        "timestamp_monotonic": ts,
        "metadata": metadata or {},
    }

    # Self-hash: the attestation digest binds ALL core fields
    canonical = json.dumps(core, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    attestation_digest = sha3_256(canonical.encode("utf-8"))

    return ScittReceipt(
        **core,
        attestation_digest=attestation_digest,
    )
